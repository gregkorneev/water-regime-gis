def set_font(run, bold=False):
    run.font.name = "Times New Roman"
    run._element.rPr.rFonts.set(qn("w:ascii"), "Times New Roman")
    run._element.rPr.rFonts.set(qn("w:hAnsi"), "Times New Roman")
    run._element.rPr.rFonts.set(qn("w:cs"), "Times New Roman")
    run.font.size = None
    run.bold = bold


def set_paragraph(paragraph, text):
    paragraph.clear()
    label, separator, remainder = text.partition(". ")
    if separator and label in HEADINGS:
        lead = paragraph.add_run(label + ". ")
        set_font(lead, bold=True)
        body = paragraph.add_run(remainder)
        set_font(body)
    else:
        run = paragraph.add_run(text)
        set_font(run)
    paragraph.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY


document = Document(PATH)
for index, text in REPLACEMENTS.items():
    set_paragraph(document.paragraphs[index], text)
document.save(PATH)
