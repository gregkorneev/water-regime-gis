def apply_font(run, bold=False):
    run.font.name = "Times New Roman"
    run._element.rPr.rFonts.set(qn("w:ascii"), "Times New Roman")
    run._element.rPr.rFonts.set(qn("w:hAnsi"), "Times New Roman")
    run._element.rPr.rFonts.set(qn("w:cs"), "Times New Roman")
    run.font.size = None
    run.bold = bold


def replace_paragraph(paragraph, text):
    paragraph.clear()
    if ". " in text and text.split(". ", 1)[0] in {
        "Аннотация", "Ключевые слова", "Введение", "Материалы и методы",
        "Результаты и обсуждение", "Заключение", "Архитектура информационной системы",
    }:
        lead, rest = text.split(". ", 1)
        lead_run = paragraph.add_run(lead + ". ")
        apply_font(lead_run, bold=True)
        body_run = paragraph.add_run(rest)
        apply_font(body_run)
    else:
        run = paragraph.add_run(text)
        apply_font(run)
    paragraph.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY


